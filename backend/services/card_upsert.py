"""Shared card upsert helper."""

from __future__ import annotations

import datetime

from sqlalchemy.orm import Session, sessionmaker

from models import Card, ImageCache, Set
from services.price_utils import PRICE_FIELDS, is_valid_price, preserve_existing_prices_for_invalid_update

PARTIAL_NULL_CLEAR_FIELDS = frozenset({"data_source_lang"})

# TCGdex's vintage Japanese sync data has a handful of garbled/mistranslated
# names (see the "TCGdex vintage JP data quality" investigation) that a full
# sync would otherwise silently re-write on every run. Corrected by manual
# cross-reference against Hareruya2's full print listing (by card number,
# since the stored name can't be trusted).
KNOWN_NAME_OVERRIDES = {
    "VS1-041_ja": "ヤナギのラプラス",
}


def _apply_known_name_override(card_data: dict) -> None:
    override = KNOWN_NAME_OVERRIDES.get(card_data.get("id"))
    if override:
        card_data["name"] = override


def _apply_set_digital_flag(db: Session, card_data: dict) -> None:
    if card_data.get("is_digital") or not card_data.get("set_id"):
        return
    set_lang = card_data.get("lang") or "en"
    set_row = db.query(Set.is_digital).filter(
        Set.tcg_set_id == card_data["set_id"],
        Set.lang == set_lang,
    ).first()
    if set_row and set_row[0]:
        card_data["is_digital"] = True


def _is_price_state_field(key: str) -> bool:
    return key.startswith("price_") or key.startswith("last_price_sync_")


def update_existing_card(
    existing: Card,
    card_data: dict,
    *,
    partial: bool = False,
    metadata_only: bool = False,
) -> Card:
    """Apply a full, partial, or catalogue-only payload to an existing card.

    ``data_source_lang`` is generated by the fallback layer, not inferred from
    a missing TCGdex field. A native brief row explicitly clears that marker so
    later sibling-language fallback cannot overwrite the native row.
    """
    for key, value in card_data.items():
        if key == "id" or (metadata_only and _is_price_state_field(key)):
            continue
        if partial and value is None and key not in PARTIAL_NULL_CLEAR_FIELDS:
            continue
        setattr(existing, key, value)
    return existing


def upsert_card(
    db: Session,
    card_data: dict,
    *,
    partial: bool = False,
    metadata_only: bool = False,
) -> Card:
    """Upsert card data; partial and metadata-only modes preserve other fields."""
    existing = db.query(Card).filter(Card.id == card_data["id"]).first()
    card_data["updated_at"] = datetime.datetime.utcnow()
    _apply_known_name_override(card_data)
    _apply_set_digital_flag(db, card_data)
    if not metadata_only:
        preserve_existing_prices_for_invalid_update(card_data, existing)
        if any(is_valid_price(card_data.get(field)) for field in PRICE_FIELDS if field.startswith("price_tcg_")):
            from services.exchange_rates import ExchangeRateUnavailable, get_exchange_rate
            # Share one lookup (including an unavailable result) across this sync
            # session. The canonical service handles refresh and saved-rate fallback.
            cache_key = "tcgplayer_usd_to_eur"
            if cache_key not in db.info:
                try:
                    db.info[cache_key] = get_exchange_rate(
                        "USD", "EUR", session_factory=sessionmaker(bind=db.get_bind())
                    )["rate"]
                except ExchangeRateUnavailable:
                    db.info[cache_key] = None
            rate = db.info[cache_key]
            if is_valid_price(rate):
                card_data["price_tcg_usd_to_eur"] = float(rate)
    has_api_image = bool(card_data.get("images_small") or card_data.get("images_large"))
    if existing:
        update_existing_card(
            existing,
            card_data,
            partial=partial,
            metadata_only=metadata_only,
        )
        if has_api_image:
            existing.custom_image_url = None
            db.query(ImageCache).filter(ImageCache.image_key.in_([
                f"card:{existing.id}:small:custom",
                f"card:{existing.id}:large:custom",
            ])).delete(synchronize_session=False)
    else:
        if metadata_only:
            card_data = {
                key: value
                for key, value in card_data.items()
                if not _is_price_state_field(key)
            }
        existing = Card(**card_data)
        db.add(existing)
    return existing
